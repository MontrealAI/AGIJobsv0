def extract_draft(text):
    marker = '{\n  "kind": "FrontierDeskDraft"'
    require(text.count(marker) == 1, "Exactly one visible portable mission draft is required")
    value, _ = json.JSONDecoder().raw_decode(text[text.index(marker):])
    require(isinstance(value, dict), "The visible mission draft must be an object")
    return value


def scripted_actions():
    actions = [{"type": "move", "x": 500, "y": 300},
               {"type": "keypress", "keys": ["TAB"]},
               {"type": "keypress", "keys": ["ENTER"]},
               {"type": "keypress", "keys": ["TAB"]},
               {"type": "keypress", "keys": ["ENTER"]},
               {"type": "wait"},
               {"type": "keypress", "keys": ["ENTER"]}]
    for supplied in [STRATEGY, EXPERIMENT, EVIDENCE, PROPOSAL, MAPPING]:
        actions += [{"type": "keypress", "keys": ["TAB"]},
                    {"type": "keypress", "keys": ["CTRL", "A"]},
                    {"type": "type", "text": supplied}]
    # Proposal, save, export, file input, and the visible-result disclosure.
    actions += [{"type": "keypress", "keys": ["TAB"]},
                {"type": "keypress", "keys": ["ENTER"]},
                {"type": "keypress", "keys": ["TAB"]},
                {"type": "keypress", "keys": ["ENTER"]},
                *[{"type": "keypress", "keys": ["TAB"]} for _ in range(3)],
                {"type": "keypress", "keys": ["ENTER"]}, {"type": "wait"}]
    return actions


def run_fixture(args, out, bundle, worker, identity, source_identity, ComputerTask, HTTPAdvisor, validate_action):
    import httpx
    task = ComputerTask.model_validate(bundle["task"])
    write(out / "executed-task.json", task.model_dump(mode="json"))
    common.require_group_observation()
    actions = scripted_actions()
    require(len(actions) <= task.max_actions, "Scripted actions exceed the sealed mission budget")
    batches = [actions[index:index + 5] for index in range(0, len(actions), 5)]
    requests, observations, fetches, performed = [], [], [], []
    journal = out / "action-journal.jsonl"
    write(journal, "")

    def retain(value):
        with journal.open("a", encoding="utf-8") as stream:
            stream.write(canonical(value) + "\n")
            stream.flush()
            os.fsync(stream.fileno())

    def reply(request):
        payload = json.loads(request.content)
        require(payload["tools"] == [{"type": "computer"}] and payload["store"] is False,
                "Use native stateless Computer Use transport")
        if requests:
            last = payload["input"][-1]
            require(last["call_id"] == f"scripted-frontier-{len(requests)}" and
                    last["output"]["type"] == "computer_screenshot",
                    "Native screenshot must bind the preceding call ID")
        requests.append({"ordinal": len(requests) + 1, "model": payload["model"],
                         "tools": payload["tools"], "store": payload["store"],
                         "requestSha256": sha(request.content)})
        retain({"type": "SCRIPTED_PROVIDER_REQUEST", **requests[-1], "cost": None})
        index = len(requests) - 1
        output = ([{"type": "computer_call", "call_id": f"scripted-frontier-{index + 1}",
                    "actions": batches[index], "pending_safety_checks": []}]
                  if index < len(batches) else [{"type": "message", "content": [
                      {"type": "output_text", "text": "SCRIPTED_TRANSPORT_TEST complete; inspect actual browser evidence."}]}])
        return httpx.Response(200, json={"status": "completed", "output": output})

    original_client = httpx.Client
    httpx.Client = lambda **kwargs: original_client(transport=httpx.MockTransport(reply), **kwargs)
    advisor = HTTPAdvisor("responses", "SCRIPTED_TRANSPORT_TEST_NOT_A_MODEL",
                          "https://provider-fixture.invalid/v1", "TEST_ONLY_NEVER_TRANSMITTED")
    started = time.monotonic()
    command = [sys.executable, str(common.LAUNCHER), "--worker", str(worker),
               "--runtime-record", str(out / "worker-runtime.json")]
    if args.chromium_executable:
        command += ["--chromium-executable", str(args.chromium_executable.resolve(strict=True))]
    environment = {key: value for key, value in os.environ.items() if key in {
        "PATH", "HOME", "LANG", "LC_ALL", "TZ", "TMPDIR", "LD_LIBRARY_PATH", "PLAYWRIGHT_BROWSERS_PATH"}}
    log = (out / "worker-stderr.log").open("x")
    os.chmod(out / "worker-stderr.log", 0o600)
    process, buffer, cleanup, failure = None, bytearray(), {}, None

    def stopped(signum, _frame):
        raise InterruptedError(f"Laboratory stop requested by signal {signum}")

    old_handlers = {kind: signal.getsignal(kind) for kind in [signal.SIGTERM, signal.SIGINT]}
    for kind in old_handlers:
        signal.signal(kind, stopped)

    def send(value):
        common.write_frame(process.stdin.fileno(), value, started + task.max_seconds)

    def observe():
        while True:
            item = common.read_frame(process.stdout.fileno(), buffer, started + task.max_seconds)
            if item.get("type") == "fetch":
                permitted = (not fetches and item.get("url") == SOURCE_URL and
                             item.get("method") == "GET")
                fetches.append({"url": item.get("url"), "method": item.get("method"),
                                "decision": "SYNTHETIC_FIXTURE_RESPONSE" if permitted else "DENIED",
                                "responseBodySha256": SOURCE_SHA256 if permitted else sha(b""),
                                "responseBytes": len(SOURCE_HTML.encode()) if permitted else 0,
                                "externalNetworkPerformed": False})
                send({"operation": "fetched", "id": item["id"], "status": 200 if permitted else 403,
                      "content_type": "text/html; charset=utf-8" if permitted else "text/plain",
                      "body": base64.b64encode(SOURCE_HTML.encode()).decode() if permitted else ""})
                continue
            require(item.get("type") == "observation", "Expected bounded worker observation")
            png = base64.b64decode(item["png"], validate=True)
            require(len(png) <= 2_000_000 and len(item["text"]) <= 100_000,
                    "Worker observation exceeds its byte budget")
            filename = f"screen-{len(observations):03d}.png"
            with (out / filename).open("xb") as stream:
                os.chmod(out / filename, 0o600)
                stream.write(png)
            observations.append({"screenshot": filename, "sha256": sha(png),
                                 "visibleTextSha256": sha(item["text"].encode()),
                                 "text": item["text"], "url": item["url"]})
            return item

    try:
        process = subprocess.Popen(command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                   stderr=log, start_new_session=True, env=environment)
        write(out / "worker-process.json", {"pid": process.pid, "processGroup": process.pid,
              "scope": "Trusted fixed worker process group; not OS containment"})
        send({"operation": "start", "html": bundle["html"]})
        observation = observe()
        for _ in range(task.max_turns):
            require(time.monotonic() - started < task.max_seconds, "Overall task deadline exceeded")
            advice = advisor.next(task, observation)
            if advice["done"]:
                break
            require(len(advice["actions"]) <= 5, "Native fixture response exceeds five actions")
            for action in advice["actions"]:
                require(len(performed) < task.max_actions, "Aggregate action budget exhausted")
                valid = validate_action(action)
                performed.append({"sequence": len(performed) + 1, "action": valid,
                                  "status": "reserved", "reservedElapsedMilliseconds":
                                      int((time.monotonic() - started) * 1000)})
                retain({"type": "ACTION", **performed[-1]})
                send({"operation": "act", "action": valid})
                observation = observe()
                performed[-1].update(status="observed", observationScreenshot=observations[-1]["screenshot"])
                retain({"type": "ACTION", **performed[-1]})
        require(advice["done"] is True, "No completion claim within the turn budget")
        require(len(fetches) == 1 and fetches[0]["decision"] == "SYNTHETIC_FIXTURE_RESPONSE",
                "The standalone source viewer must use exactly one allowed synthetic GET and no other resource")
        draft = extract_draft(observation["text"])
    except BaseException as error:
        failure = {"type": type(error).__name__, "message": str(error)}
        raise
    finally:
        cleanup = common.terminate_group(process) if process is not None else {
            "leaderExited": True, "liveGroupMembers": [], "groupClosed": True, "workerNotLaunched": True}
        log.close()
        httpx.Client = original_client
        for kind, handler in old_handlers.items():
            signal.signal(kind, handler)
        if failure:
            write(out / "failure-evidence.json", {"failure": failure, "observations": observations,
                  "actions": performed, "cleanup": cleanup, "liveProvider": False,
                  "productionApproved": False, "authority": []})
    require(cleanup["groupClosed"], "Worker group cleanup failed")
    write(out / "worker-cleanup.json", cleanup)
    review = review_draft(args.node, bundle["mission"], draft)
    write(out / "observed-draft.json", draft)
    write(out / "visible-text.txt", observation["text"])
    write(out / "review.json", review)
    require(review["accepted"], "Independent content review rejected the scripted transport draft")
    require(jobs_sources() == source_identity, "Jobs source changed during the run; retain history and start a fresh run")
    require(common.alpha_source(args.alpha_source.resolve())[1] == identity,
            "Alpha source changed during the run; retain history and start a fresh run")
    evidence = {"schema": "agijobsv0/successor-frontier-computer-lab/v1",
                "scope": "HOST_SCRIPTED_TRANSPORT_TEST_NOT_RESEARCH_OR_DOCKER_QUALIFICATION",
                "browserExecuted": True, "decisionSource": "SCRIPTED_NATIVE_COMPUTER_CALL_FIXTURE",
                "liveProvider": False, "providerMode": "responses-computer-fixture",
                "alphaSource": identity, "jobsSources": source_identity,
                "sourceStableDuringRun": True, "alphaSourceStableDuringRun": True,
                "jobsCheckoutCommit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
                "bindings": {"missionDigest": bundle["mission"]["digest"],
                             "taskSha256": sha(canonical(bundle["task"]).encode()),
                             "htmlSha256": sha(bundle["html"].encode()),
                             "workspaceDigest": review["workspace"]["digest"]},
                "runtime": {"browser": json.loads(common.bounded_read(out / "worker-runtime.json", 20000)),
                            "browserRecordSha256": sha((out / "worker-runtime.json").read_bytes()),
                            "python": sys.version.split()[0],
                            **{name: importlib.metadata.version(name) for name in ["playwright", "pydantic", "httpx", "cryptography"]},
                            "node": subprocess.check_output([args.node, "--version"], text=True).strip(),
                            "chromiumExecutable": str(args.chromium_executable.resolve()) if args.chromium_executable else "Playwright-managed default",
                            "chromiumExecutableSha256": sha(args.chromium_executable.read_bytes()) if args.chromium_executable else None,
                            "workerEnvironmentKeys": sorted(environment)},
                "observedDraft": draft, "actions": performed, "observations": observations,
                "providerFixtureRequests": requests, "brokerFetches": fetches,
                "externalFetches": [], "externalNetworkRequests": 0,
                "sourceViewer": {"mode": "SCRIPTED_BROKER_SOURCE_FIXTURE_NOT_LIVE_WEBSITE_CONTENTS",
                                 "url": SOURCE_URL, "method": "GET", "responseBodySha256": SOURCE_SHA256,
                                 "screenshot": observations[6]["screenshot"],
                                 "screenshotSha256": observations[6]["sha256"],
                                 "iframeDOMExtracted": False,
                                 "scope": "Actual screenshot after native source-view action; the synthetic body is supplied by this fixture."},
                "cleanup": cleanup, "elapsedSeconds": time.monotonic() - started,
                "usage": advisor.usage_events, "cost": None, "billing": "UNKNOWN_NOT_A_LIVE_PROVIDER_RUN",
                "review": review, "researchExperimentExecuted": False, "freshProtectedProof": False,
                "independentModelQualityEstablished": False, "productionApproved": False,
                "settlementApproved": False, "authority": [],
                "artifacts": {path.name: sha(path.read_bytes()) for path in out.iterdir() if path.is_file()}}
    write(out / "evidence.json", evidence)
    return {"accepted": True, "browserExecuted": True, "liveProvider": False,
            "scriptedTransportOnly": True, "tamperedMissionRejected": True,
            "actions": len(performed), "screenshots": len(observations),
            "brokerFetches": len(fetches), "externalNetworkRequests": 0,
            "externalFetches": 0, "workerTerminated": cleanup["groupClosed"],
            "evidenceDirectory": str(out)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--alpha-source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--node", default="node")
    parser.add_argument("--chromium-executable", type=Path)
    parser.add_argument("--prepare-only", action="store_true")
    args = parser.parse_args()
    out = args.output.resolve()
    require(not out.exists(), "Choose a new evidence directory; history is never overwritten")
    worker, identity = common.alpha_source(args.alpha_source.resolve(strict=True))
    ComputerTask, HTTPAdvisor, validate_action = common.load_alpha_computer(args.alpha_source.resolve())
    source_identity = jobs_sources()
    bundle = build_bundle(args.node)
    ComputerTask.model_validate(bundle["task"])
    require(jobs_sources() == source_identity, "Source changed during preparation")
    out.mkdir(parents=True, mode=0o700)
    export_bundle(out, bundle, identity, source_identity)
    if args.prepare_only:
        print(json.dumps({"prepared": True, "executed": False, "liveProvider": False,
                          "output": str(out), "authority": []}))
        return 0
    try:
        result = run_fixture(args, out, bundle, worker, identity, source_identity,
                             ComputerTask, HTTPAdvisor, validate_action)
    except BaseException as error:
        if not (out / "failure-evidence.json").exists():
            write(out / "failure-evidence.json", {"failure": {"type": type(error).__name__, "message": str(error)},
                  "scope": "Retained incomplete scripted host laboratory; inspect partial artifacts before a new run",
                  "liveProvider": False, "productionApproved": False, "authority": []})
        raise
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
